/**
 * INTRODUCTION TO DART
 * 
 * What is Dart?
 * Dart is a modern, object-oriented programming language developed by Google.
 * It was first released in 2011 and is designed for building web, mobile, 
 * desktop, and server applications.
 * 
 * Key Features of Dart:
 * 1. Object-Oriented: Everything in Dart is an object, including numbers and functions
 * 2. Strongly Typed: Dart has a strong type system, but also supports type inference
 * 3. Null Safety: Dart 2.12+ includes null safety features to prevent null errors
 * 4. Garbage Collected: Automatic memory management
 * 5. Platform Independent: Can run on multiple platforms
 * 6. Fast: Can compile to native code for better performance
 * 
 * Where is Dart Used?
 * - Flutter Framework: Primary language for Flutter mobile app development
 * - Web Development: Can compile to JavaScript
 * - Server-Side: Can be used for backend development
 * - Command Line Tools: For building CLI applications
 * 
 * Dart vs Other Languages:
 * - Similar syntax to Java, C#, and JavaScript
 * - Modern features like async/await, streams, and isolates
 * - Strong tooling support with Dart SDK
 */

